fn decode_mutated<const N: usize>(seed: [u8; N], mutations: &[u8]) {
    let mut near_valid = seed;
    for (target, mutation) in near_valid.iter_mut().zip(mutations) {
        *target ^= mutation;
    }
    let _ = decode_control_frame(&near_valid);
}

fuzz_target!(|data: &[u8]| {
    let _ = decode_control_frame(data);

    decode_mutated(PUBLISHED_HELLO_FRAME, data);
    decode_mutated(PUBLISHED_START_STREAM_FRAME, data);
    decode_mutated(PUBLISHED_STOP_STREAM_FRAME, data);
    decode_mutated(PUBLISHED_STREAM_STATUS_FRAME, data);
    decode_mutated(PUBLISHED_CONTROL_ERROR_FRAME, data);
});
