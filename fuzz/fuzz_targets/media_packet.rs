#![no_main]

use libfuzzer_sys::fuzz_target;
use sonimesh_protocol::parse_media_packet;

const PUBLISHED_MEDIA_DATAGRAM: [u8; 73] = [
    0x53, 0x4E, 0x4D, 0x53, 0x01, 0x02, 0x00, 0x24, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08,
    0x0A, 0x0B, 0x0C, 0x0D, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03, 0xC0,
    0x00, 0x25, 0x0E, 0x0F, 0x7C, 0xCE, 0x62, 0xEA, 0x96, 0x0F, 0xC2, 0x7C, 0xF5, 0xA6, 0xFF, 0xCE,
    0x2A, 0xA5, 0x93, 0x43, 0xA5, 0xF1, 0x29, 0x97, 0x79, 0x13, 0x96, 0xCA, 0x10, 0xBD, 0xFC, 0x7C,
    0xC0, 0x60, 0xC9, 0xDF, 0xE4, 0x9F, 0xD6, 0x71, 0x31,
];

fuzz_target!(|data: &[u8]| {
    let _ = parse_media_packet(data);

    let mut near_valid = PUBLISHED_MEDIA_DATAGRAM;
    for (target, mutation) in near_valid.iter_mut().zip(data) {
        *target ^= mutation;
    }
    let _ = parse_media_packet(&near_valid);
});
